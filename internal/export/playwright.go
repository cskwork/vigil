// ariaRoles is the set Playwright's getByRole accepts; anything else falls back to
// a [role=...] CSS locator so the generated file stays valid TypeScript.
var ariaRoles = map[string]bool{}

func init() {
	for _, r := range strings.Fields(`alert alertdialog application article banner blockquote button caption cell checkbox code
		columnheader combobox complementary contentinfo definition deletion dialog directory document emphasis feed figure form
		generic grid gridcell group heading img insertion link list listbox listitem log main marquee math meter menu menubar
		menuitem menuitemcheckbox menuitemradio navigation none note option paragraph presentation progressbar radio radiogroup
		region row rowgroup rowheader scrollbar search searchbox separator slider spinbutton status strong subscript superscript
		switch tab table tablist tabpanel term textbox time timer toolbar tooltip tree treegrid treeitem`) {
		ariaRoles[r] = true
	}
}

var plainID = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_-]*$`)

// note writes a comment line before the statement being built.
func (g *gen) note(format string, a ...any) { g.line("// "+format, a...) }

// loc renders a locator expression on the active page; mapping caveats become a
// comment line above the statement.
func (g *gen) loc(l *dsl.Locator) string {
	s, note := Locator(g.pv, l)
	if note != "" {
		g.note("%s", note)
	}
	return s
}

// Locator renders a dsl locator as a Playwright locator chain on page variable pv.
// note is non-empty when the mapping is approximate or needs attention (TODO test.fixme).
func Locator(pv string, l *dsl.Locator) (s, note string) {
	if l == nil {
		return pv + ".locator('body')", "TODO test.fixme: locator missing"
	}
	by := l.By
	if by == "" {
		switch {
		case l.Role != "":
			by = "role"
		case l.Text != "":
			by = "text"
		case l.Name != "":
			by = "label"
		default:
			by = "test_id"
		}
	}
	switch by {
	case "test_id":
		s = fmt.Sprintf("%s.getByTestId(%s)", pv, tsString(l.Value))
		if l.By == "" {
			note = "locator.by unset: vigil also tries #id and a css selector for this value"
		}
	case "role":
		if ariaRoles[l.Role] {
			s = fmt.Sprintf("%s.getByRole(%s%s)", pv, tsString(l.Role), roleOpts(l))
		} else {
			s = fmt.Sprintf("%s.locator(%s)", pv, tsString(fmt.Sprintf(`[role=%s]`, cssString(l.Role))))
			if l.Name != "" {
				s += fmt.Sprintf(".filter({ hasText: %s })", tsString(l.Name))
			}
			note = "TODO test.fixme: role " + oneLine(l.Role) + " is not an ARIA role known to getByRole; using a [role=...] css locator"
		}
	case "label":
		name := first(l.Name, l.Text, l.Value)
		s = fmt.Sprintf("%s.getByLabel(%s%s).or(%s.getByPlaceholder(%s%s))", pv, tsString(name), exactOpt(l.Exact), pv, tsString(name), exactOpt(l.Exact))
		note = "label locator: getByPlaceholder is the fallback because vigil also matches placeholder text"
	case "id":
		if plainID.MatchString(l.Value) {
			s = fmt.Sprintf("%s.locator(%s)", pv, tsString("#"+l.Value))
		} else {
			s = fmt.Sprintf("%s.locator(%s)", pv, tsString("[id="+cssString(l.Value)+"]"))
		}
	case "text":
		s = fmt.Sprintf("%s.getByText(%s%s)", pv, tsString(first(l.Text, l.Value)), exactOpt(l.Exact))
	case "href":
		op := "*="
		if l.Exact {
			op = "="
		}
		s = fmt.Sprintf("%s.locator(%s)", pv, tsString("a[href"+op+cssString(l.Value)+"]"))
	case "css":
		s = fmt.Sprintf("%s.locator(%s)", pv, tsString(l.Value))
	default:
		s = pv + ".locator('body')"
		note = "TODO test.fixme: unknown locator by " + oneLine(l.By)
	}
	if l.Nth > 0 {
		s += fmt.Sprintf(".nth(%d)", l.Nth)
	}
	return s, note
}

func roleOpts(l *dsl.Locator) string {
	var parts []string
	if l.Name != "" {
		parts = append(parts, "name: "+tsString(l.Name))
	}
	if l.Exact {
		parts = append(parts, "exact: true")
	}
	if len(parts) == 0 {
		return ""
	}
	return ", { " + strings.Join(parts, ", ") + " }"
}

func exactOpt(exact bool) string {
	if exact {
		return ", { exact: true }"
	}
	return ""
}

func first(xs ...string) string {
	for _, x := range xs {
		if x != "" {
			return x
		}
	}
	return ""
}

// ---- options / timeouts --------------------------------------------------------

// timeoutMs parses a DSL duration; ok is false when unset or invalid.
func timeoutMs(raw string) (int64, bool) {
	if raw == "" {
		return 0, false
	}
	d, err := time.ParseDuration(raw)
	if err != nil || d <= 0 {
		return 0, false
	}
	return d.Milliseconds(), true
}

// opts renders `{ timeout: N }` or "" for a call with no other arguments.
func (g *gen) opts(raw string) string {
	if ms, ok := timeoutMs(raw); ok {
		return fmt.Sprintf("{ timeout: %d }", ms)
	}
	if raw != "" {
		g.note("TODO test.fixme: invalid timeout %q ignored", oneLine(raw))
	}
	return ""
}

// optsArg renders `, { timeout: N }` for a call that already has arguments.
func (g *gen) optsArg(raw string) string {
	if o := g.opts(raw); o != "" {
		return ", " + o
	}
	return ""
}

func (g *gen) url(u string) string {
	if strings.HasPrefix(u, "http://") || strings.HasPrefix(u, "https://") {
		return tsString(u)
	}
	return "BASE_URL + " + tsString(u)
}

func urlRegexp(u *dsl.URLAssert) string {
	if u.Matches != "" {
		return tsRegexp(u.Matches)
	}
	return tsRegexp(regexp.QuoteMeta(u.Contains))
}

// ---- json path ------------------------------------------------------------------

// jsonPathExpr converts the DSL json path ($, .key, [N], [*] first element,
// ["key"]) into an optional-chained TypeScript accessor on root.
func jsonPathExpr(root, path string) (string, error) {
	if !strings.HasPrefix(path, "$") {
		return "", fmt.Errorf("path must start with $")
	}
	rest := path[1:]
	var b strings.Builder
	b.WriteString(root)
	for len(rest) > 0 {
		switch rest[0] {
		case '.':
			end := strings.IndexAny(rest[1:], ".[")
			var name string
			if end < 0 {
				name, rest = rest[1:], ""
			} else {
				name, rest = rest[1:1+end], rest[1+end:]
			}
			if name == "" {
				return "", fmt.Errorf("empty key segment")
			}
			fmt.Fprintf(&b, "?.[%s]", tsString(name))
		case '[':
			end := strings.IndexByte(rest, ']')
			if end < 0 {
				return "", fmt.Errorf("unterminated [ in %q", rest)
			}
			inner := rest[1:end]
			rest = rest[end+1:]
			switch {
			case inner == "*":
				b.WriteString("?.[0]")
			case len(inner) >= 2 && (inner[0] == '"' || inner[0] == '\'') && inner[len(inner)-1] == inner[0]:
				fmt.Fprintf(&b, "?.[%s]", tsString(inner[1:len(inner)-1]))
			default:
				n, err := strconv.Atoi(inner)
				if err != nil || n < 0 {
					return "", fmt.Errorf("bad index [%s]", inner)
				}
				fmt.Fprintf(&b, "?.[%d]", n)
			}
		default:
			return "", fmt.Errorf("unexpected %q in path", rest)
		}
	}
	return b.String(), nil
}

// ---- escaping ------------------------------------------------------------------

// tsString renders s as a single-quoted TypeScript string literal.
func tsString(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '\'':
			b.WriteString(`\'`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '\u2028', '\u2029': // line separators break JS literals
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('\'')
	return b.String()
}

func tsStringArray(xs []string) string {
	parts := make([]string, len(xs))
	for i, x := range xs {
		parts[i] = tsString(x)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// tsRegexp renders `new RegExp(<JSON string>)` so any pattern survives as-is.
func tsRegexp(pattern string) string {
	return "new RegExp(" + jsonString(pattern) + ")"
}

func jsonString(s string) string {
	return jsLiteral(s)
}

// jsLiteral renders a JSON-compatible value as a JavaScript literal (map keys sorted
// by encoding/json, so the output is deterministic).
func jsLiteral(v any) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return "null"
	}
	return strings.TrimRight(buf.String(), "\n")
}

// cssString renders s as a double-quoted CSS string (for attribute selectors).
func cssString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\a `).Replace(s) + `"`
}

// oneLine keeps comment text on one line and closes no comment early.
func oneLine(s string) string {
	s = strings.NewReplacer("\r\n", " ", "\n", " ", "\r", " ", "*/", "* /").Replace(s)
	return strings.TrimSpace(s)
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}
